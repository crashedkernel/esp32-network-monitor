"""Generate gzip flash assets from web/; run after changing dashboard files."""
from pathlib import Path
import gzip
root=Path(__file__).resolve().parents[1]
files={'DASHBOARD_HTML':'index.html','UI_CSS':'ui.css','THEME_JS':'theme.js','DASHBOARD_JS':'dashboard.js','ADMIN_JS':'admin.js','TIMEZONES_JSON':'timezones.json'}
lines=['#pragma once','#include <Arduino.h>','// Generated by tools/build_web_assets.py; edit web/ sources instead.']
for symbol,name in files.items():
    data=gzip.compress((root/'web'/name).read_bytes(),compresslevel=9,mtime=0)
    lines.append('const uint8_t '+symbol+'[] PROGMEM = {')
    lines.extend('  '+','.join(str(b) for b in data[i:i+24])+',' for i in range(0,len(data),24))
    lines.append('};')
(root/'NetworkMonitor/WebAssets.h').write_text('\n'.join(lines)+'\n')
print('Generated compressed dashboard assets.')
